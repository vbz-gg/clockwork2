#!/usr/bin/env bun
/**
 * Writes `packages/engine/src/key-codes.ts`: every `KeyboardEvent.code` value
 * a manifest may bind.
 *
 * The list is the UI Events KeyboardEvent code Values Recommendation, read
 * from the `id="code-..."` anchor each table row carries. A binding's code is
 * checked against it, so a typo such as `Arrowleft`, which no browser sends,
 * is refused at upload rather than becoming a key that never fires.
 * `Unidentified` is left out: the specification allows it only when a
 * browser cannot tell which key was pressed, so binding it means nothing.
 *
 * Run it by hand when a new Recommendation is published, and commit the
 * result. It is not part of the build, because the build must not depend on
 * the network.
 *
 *   bun run scripts/gen-key-codes.ts
 */

import { join } from "node:path"

/** The dated Recommendation, so the list is a fixed document, not a moving one. */
export const SOURCE = "https://www.w3.org/TR/2025/REC-uievents-code-20250422/"

const OUT = join(import.meta.dir, "..", "packages/engine/src/key-codes.ts")

/** The codes a page lists, in the order of first appearance, without `Unidentified`. */
export function codesIn(html: string): readonly string[] {
  const seen = new Set<string>()
  for (const match of html.matchAll(/id="code-([A-Za-z0-9]+)"/g)) {
    const code = match[1] as string
    if (code !== "Unidentified") seen.add(code)
  }
  return [...seen].sort()
}

export function render(codes: readonly string[]): string {
  const lines = codes.map((code) => `  "${code}",`).join("\n")
  return `/**
 * Every \`KeyboardEvent.code\` value a manifest may bind: the UI Events
 * KeyboardEvent code Values Recommendation, without \`Unidentified\`.
 *
 * Generated by \`scripts/gen-key-codes.ts\` from
 * ${SOURCE}
 * Do not edit by hand.
 */
export const KEY_CODES: readonly string[] = [
${lines}
]
`
}

if (import.meta.main) {
  const response = await fetch(SOURCE)
  if (!response.ok) {
    throw new Error(`fetching ${SOURCE} answered ${response.status}`)
  }
  const codes = codesIn(await response.text())
  if (codes.length < 100) {
    throw new Error(
      `found only ${codes.length} codes at ${SOURCE}; the page's markup has changed`,
    )
  }
  await Bun.write(OUT, render(codes))
  process.stdout.write(`wrote ${codes.length} key codes to ${OUT}\n`)
}
